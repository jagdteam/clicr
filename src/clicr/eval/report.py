"""Render the README eval section from results JSON (used by scripts/render_eval_table.py)."""

from __future__ import annotations

from collections.abc import Sequence
from decimal import ROUND_FLOOR, Decimal

from clicr.config import Settings

START = "<!-- eval:start -->"
END = "<!-- eval:end -->"
COLUMNS = "| {first} | Recall@5 | Recall@10 | MRR | p95 retrieval ms |\n|---|---|---|---|---|"
ABLATION_COLUMNS = (
    "| Config | Recall@5 | Recall@10 | Context recall | MRR | p95 retrieval ms |\n"
    "|---|---|---|---|---|---|"
)
CONTEXT_NOTE = (
    "Context recall: share of gold spans anywhere in the final list the model sees"
    " (top 10 plus graph additions); Recall@k counts only the top k."
)


def default_embedder(settings: Settings | None = None) -> str:
    """The embedder name the shipped defaults use (as stored in results rows)."""
    s = settings or Settings()
    if s.embed_provider == "fastembed":
        return f"fastembed:{s.fastembed_model}"
    return f"{s.embed_provider}:{s.embed_model}"


def _fmt(value: float | None, digits: int = 3) -> str:
    return "-" if value is None else f"{value:.{digits}f}"


def _floor4(value: float) -> str:
    """4 places rounded DOWN: the published threshold never abstains where the run did not."""
    return str(Decimal(repr(value)).quantize(Decimal("0.0001"), rounding=ROUND_FLOOR))


def _cells(row: dict, context: bool = False) -> str:
    overall = row["metrics"]["overall"]
    p95 = row.get("latency", {}).get("total", {}).get("p95")
    keys = ["recall@5", "recall@10", *(["recall@final"] if context else []), "mrr"]
    return " | ".join([*(_fmt(overall.get(k)) for k in keys), _fmt(p95, 1)])


def _shown_rows(results: dict, default: str) -> tuple[str, list[dict]]:
    """The embedder the ablation table shows, and its rows."""
    rows = results.get("rows", [])
    embedders = list(dict.fromkeys(r["embedder"] for r in rows))
    shown = default if default in embedders else (embedders[0] if embedders else default)
    return shown, [r for r in rows if r["embedder"] == shown]


def _answerable(results: dict, default: str) -> int:
    mine = _shown_rows(results, default)[1]
    return (mine[0]["metrics"]["overall"].get("n") or 0) if mine else 0


def _suite_section(results: dict, default: str) -> list[str]:
    rows = results.get("rows", [])
    shown, mine = _shown_rows(results, default)
    ref = results.get("ref") or ""
    commit = (results.get("commit") or "")[:7]
    label = commit if ref == commit else f"{ref} @ {commit}"
    out = [f"### {results['suite']} ({label})", ""]
    n = mine[0]["metrics"]["overall"].get("n") if mine else None
    out.append(
        f"Ablation with embedder `{shown}`: each row adds one stage to the row above,"
        f" except `+rerank`, which is measured on top of `+hybrid` and not carried into later rows"
        f" ({n} answerable questions)."
    )
    out += ["", ABLATION_COLUMNS]
    out += [f"| {r['config']} | {_cells(r, context=True)} |" for r in mine]
    out += ["", CONTEXT_NOTE]

    best = (results.get("best") or {}).get("config")
    if best:
        out += ["", f"Embedders on the best config (`{best}`):", ""]
        out.append(COLUMNS.format(first="Embedder"))
        out += [f"| {r['embedder']} | {_cells(r)} |" for r in rows if r["config"] == best]

    abstain = results.get("abstain")
    if abstain and abstain.get("threshold") is not None:
        out += [
            "",
            f"Abstain: threshold {_floor4(abstain['threshold'])} on the {abstain['signal']}"
            f" (`{abstain['config']}`, `{abstain['embedder']}`): precision"
            f" {_fmt(abstain['precision'])}, recall {_fmt(abstain['recall'])},"
            f" F1 {_fmt(abstain['f1'])} over {abstain['n_unanswerable']} unanswerable questions.",
        ]

    answers = results.get("answers")
    if answers:
        s = answers.get("summary", {})
        line = (
            f"Answer track (`{answers['chat_model']}` on `{answers['config']}`,"
            f" `{answers['embedder']}`): citation accuracy {_fmt(s.get('citation_accuracy'))},"
            f" answers citing a gold span {_fmt(s.get('cited_any_gold'))},"
            f' "not found" on unanswerable questions {_fmt(s.get("unanswerable_not_found"))}.'
        )
        if answers.get("judge_model"):
            line += (
                f" LLM judge `{answers['judge_model']}` (the same local model family as the"
                f" answerer, so expect bias): faithfulness {_fmt(s.get('faithfulness'), 2)}/5,"
                f" correctness {_fmt(s.get('correctness'), 2)}/5."
            )
        out += ["", line]
    return out


def render_section(results: Sequence[dict], default: str) -> str:
    """Markdown for every suite: most answerable questions first, ties by suite name."""
    lines = [
        "## Evaluation results",
        "",
        "Generated by `scripts/render_eval_table.py` from `eval/results/*.json`; do not edit.",
    ]
    if not results:
        lines += ["", "No evaluation results yet."]
    for res in sorted(results, key=lambda r: (-_answerable(r, default), r["suite"])):
        lines += ["", *_suite_section(res, default)]
    return "\n".join(lines)


def replace_section(readme: str, section: str) -> str:
    """Put `section` between the markers, appending the markers at the end when absent."""
    block = f"{START}\n{section.rstrip()}\n{END}"
    has_start, has_end = START in readme, END in readme
    if has_start != has_end:
        raise ValueError(f"README has only one of {START} / {END}")
    if not has_start:
        return readme.rstrip("\n") + "\n\n" + block + "\n"
    i = readme.index(START)
    j = readme.index(END, i) + len(END)
    return readme[:i] + block + readme[j:]
